import * as assert from 'node:assert/strict';
import {mkdtempSync, writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import * as path from 'node:path';
import {before, describe, it} from 'node:test';

import {SemanticAnalyzer} from '../semantics/analyzer';

// A stand-in for the standard library: just enough of builtin and one other
// module to resolve names and imports.
const LIBS = [
  {name: 'builtin', path: '/stdlib/builtin.zn', text: 'function cat(args) args\nfunction str(x) x\n'},
  {name: 'io', path: '/stdlib/io.zn', text: 'function println(a) a\n'},
  {name: 'async', path: '/stdlib/async.zn', text: 'class Actor {}\n'},
  {name: 'build', path: '/stdlib/build.zn', text: 'class WithBuilder {}\n'},
];

let analyzer: SemanticAnalyzer;
let workspace: string;

before(async () => {
  workspace = mkdtempSync(path.join(tmpdir(), 'zinnia-diagnostics-'));
  writeFileSync(path.join(workspace, 'helper.zn'), 'function help() 1\n');
  analyzer = new SemanticAnalyzer();
  await analyzer.init(
      [{uri: 'file://' + workspace, name: 'workspace'}], async () => LIBS);
});

// Returns the problems in [lines] as 'row:col message' (1-based), leaving
// out hints of unused code.
async function problems(...lines: string[]): Promise<string[]> {
  return problemsWithHints(...lines).then(
      ps => ps.filter(p => !/ is (imported|assigned) but never used\.$/.test(p)));
}

// Returns all the problems in [lines] as 'row:col message' (1-based).
async function problemsWithHints(...lines: string[]): Promise<string[]> {
  const info = await analyzer.parseDocument({
    textDocument: {uri: 'file://' + path.join(workspace, 'test.zn')},
    text: lines.join('\n') + '\n',
  });
  return info.problems.map(
      p => `${(p.row ?? -1) + 1}:${(p.col ?? -1) + 1} ${p.message}`);
}

describe('undefined names', () => {
  it('reports a name that is never defined', async () => {
    assert.deepEqual(
        await problems('x = 1', 'y = x + z'),
        ['2:9 \'z\' is not defined.']);
  });

  it('accepts builtins and names defined later', async () => {
    assert.deepEqual(
        await problems(
            'cb = () -> later + 1', 'later = 2', 'cat(str(later), self, args)'),
        []);
  });

  it('accepts names defined natively and generated by annotations', async () => {
    assert.deepEqual(
        await problems(
            'import async', 'import build', '@async.Actor', 'class Counter {}',
            '@build.WithBuilder', 'class Dog {}',
            'x = (CounterProxy, DogBuilder, builder_of_Dog, Int, __native())'),
        []);
  });

  it('accepts class names after an unknown annotation', async () => {
    assert.deepEqual(
        await problems(
            'class Gen {', '  method annotate(c) c', '}', '@Gen', 'class A {}',
            'x = GeneratedClass'),
        []);
  });

  it('accepts unqualified members in methods', async () => {
    assert.deepEqual(
        await problems(
            'class A {', '  field f', '  method m() cat(f, n(), class(), hash())',
            '  method n() 1', '}'),
        []);
  });

  it('accepts inherited members of an unknown superclass', async () => {
    assert.deepEqual(
        await problems(
            'import io', 'class B : io.Base {', '  method m() inherited', '}'),
        []);
  });
});

describe('builtin\'s imports', () => {
  it('are visible in every module, as the runtime looks names up in builtin\'s members', async () => {
    const analyzer = new SemanticAnalyzer();
    await analyzer.init([], async () => [
      {name: 'builtin', path: '/stdlib/builtin.zn', text: 'import io\nfunction cat(args) args\n'},
      {name: 'io', path: '/stdlib/io.zn', text: 'function println(a) a\n'},
    ]);
    const info = await analyzer.parseDocument(
        {textDocument: {uri: 'file:///uses_io.zn'}, text: 'io.println(1)\nnet.x()\n'});
    assert.deepEqual(info.problems.map(p => p.message), ['\'net\' is not defined.']);
  });
});

describe('top-level variables in functions', () => {
  it('reports a top-level variable used in a function', async () => {
    assert.deepEqual(await problems('limit = 3', 'function f() limit'), [
      '2:14 \'limit\' is a variable of the module\'s top-level code, which ' +
      'functions and methods can\'t see; make it a module member with ' +
      '\'self.limit = ...\'.'
    ]);
  });

  it('accepts module members, imports, functions and classes', async () => {
    assert.deepEqual(
        await problems(
            'import io', 'self.LIMIT = 3', 'class C {}', 'function g() 1',
            'function f() cat(LIMIT, io, C, g())'),
        []);
  });

  it('treats an assignment in a function as a new variable', async () => {
    assert.deepEqual(
        await problems('x = 1', 'function f() {', '  x = 2', '  return x', '}'),
        []);
  });

  it('lets lambdas see top-level variables', async () => {
    assert.deepEqual(await problems('x = 1', 'f = () -> x + 1'), []);
  });
});

describe('const', () => {
  it('reports reassigning a const', async () => {
    assert.deepEqual(
        await problems('const c = 1', 'c = 2', 'g = () {', '  c = 3', '}'),
        ['2:1 Cannot reassign const \'c\'.', '4:3 Cannot reassign const \'c\'.']);
  });

  it('allows the same name in a function', async () => {
    assert.deepEqual(
        await problems('const c = 1', 'function f() {', '  c = 2', '}'), []);
  });
});

describe('argument counts', () => {
  it('reports too many or too few arguments', async () => {
    assert.deepEqual(
        await problems(
            'function two(a, b) a', 'class P {', '  new(field x, field y) {}', '}',
            'two(1, 2, 3)', 'two()', 'P(1, 2, 3)'),
        [
          '5:1 \'two\' takes 2 arguments but 3 were given; the extra ones are ' +
              'ignored.',
          '6:1 \'two\' takes 2 arguments but 0 were given; the missing ones ' +
              'are None.',
          '7:1 \'P\' takes 2 arguments but 3 were given; the extra ones are ' +
              'ignored.',
        ]);
  });

  it('accepts calls that may pass or receive tuples', async () => {
    assert.deepEqual(
        await problems(
            'function two(a, b) a', 'function one(a) a',
            'function dflt(a, b=2) a', 't = (1, 2)', 'two(t)', 'one(1, 2, 3)',
            'dflt(1, 2)', 'two(a: 1, b: 2)'),
        []);
  });

  it('accepts default parameters that refer to earlier ones', async () => {
    assert.deepEqual(
        await problems('class A {', '  method m(a, b=a) b', '}'), []);
  });
});

describe('imports', () => {
  it('reports modules that can\'t be found', async () => {
    assert.deepEqual(
        await problems('import io', 'import helper', 'import missing',
                       'import \'nowhere/thing\''),
        [
          '3:8 Module \'missing\' not found.',
          '4:8 Module \'nowhere/thing\' not found.',
        ]);
  });
});

describe('unused and unreachable code', () => {
  it('reports unused imports and variables of functions', async () => {
    assert.deepEqual(
        await problemsWithHints(
            'import io', 'import async', 'x = 1', 'function f(a) {', '  y = 2',
            '  _z = 3', '  w = 4', '  return w + a', '}', 'q = async.x'),
        [
          '1:8 \'io\' is imported but never used.',
          '5:3 \'y\' is assigned but never used.',
        ]);
  });

  it('allows unused catch variables and loop variables named _', async () => {
    assert.deepEqual(
        await problemsWithHints(
            'function f(m) {', '  try {', '    m()', '  } catch e {', '  }',
            '  for (_, v) in m {', '    cat(v)', '  }', '}'),
        []);
  });

  it('counts uses in lambdas and before the definition', async () => {
    assert.deepEqual(
        await problemsWithHints(
            'function f() {', '  g = () -> later', '  later = 1', '  return g', '}'),
        []);
  });

  it('reports code after a return', async () => {
    const info = await analyzer.parseDocument({
      textDocument: {uri: 'file://' + path.join(workspace, 'unreachable.zn')},
      text: 'function f() {\n  return 1\n  cat(2)\n  cat(3)\n}\n',
    });
    assert.deepEqual(
        info.problems.map(p => [p.message, p.row, p.col, p.endRow, p.endCol]),
        [['Unreachable code.', 2, 2, 3, 8]]);
  });
});
